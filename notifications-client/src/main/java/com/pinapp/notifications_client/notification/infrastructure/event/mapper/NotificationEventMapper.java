package com.pinapp.notifications_client.notification.infrastructure.event.mapper;


import com.pinapp.notifications_client.autogenerated.events.notification.NotificationEmailEvent;
import com.pinapp.notifications_client.autogenerated.events.notification.NotificationPushCreatedEvent;
import com.pinapp.notifications_client.autogenerated.events.notification.NotificationSmsCreatedEvent;
import com.pinapp.notifications_client.common.infrastructure.event.util.MapperUtils;
import com.pinapp.notifications_client.notification.domain.event.NotificationEmailCreatedDomainEvent;
import com.pinapp.notifications_client.notification.domain.event.NotificationPushCreatedDomainEvent;
import com.pinapp.notifications_client.notification.domain.event.NotificationSmsCreatedDomainEvent;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingConstants;
import org.mapstruct.ReportingPolicy;


@Mapper(
        componentModel = MappingConstants.ComponentModel.SPRING,
        unmappedTargetPolicy = ReportingPolicy.ERROR
)
public interface NotificationEventMapper extends MapperUtils {

    @Mapping(
            target = "id",
            expression = "java(java.util.UUID.randomUUID().getMostSignificantBits() & Long.MAX_VALUE)"
    )
    @Mapping(
            target = "timestamp",
            expression = "java(System.currentTimeMillis())"
    )
    NotificationEmailEvent mapToNotificationEmailEvent(
            NotificationEmailCreatedDomainEvent event
    );

    @Mapping(
            target = "id",
            expression = "java(java.util.UUID.randomUUID().getMostSignificantBits() & Long.MAX_VALUE)"
    )
    @Mapping(
            target = "timestamp",
            expression = "java(System.currentTimeMillis())"
    )
    NotificationSmsCreatedEvent mapToNotificationSmsCreatedEvent(
            NotificationSmsCreatedDomainEvent event
    );

    @Mapping(
            target = "id",
            expression = "java(java.util.UUID.randomUUID().getMostSignificantBits() & Long.MAX_VALUE)"
    )
    @Mapping(
            target = "timestamp",
            expression = "java(System.currentTimeMillis())"
    )
    NotificationPushCreatedEvent mapToNotificationPushCreatedEvent(
            NotificationPushCreatedDomainEvent event
    );
}

