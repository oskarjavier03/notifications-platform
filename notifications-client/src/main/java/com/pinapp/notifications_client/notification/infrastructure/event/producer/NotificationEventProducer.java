package com.pinapp.notifications_client.notification.infrastructure.event.producer;


import com.pinapp.notifications_client.autogenerated.events.notification.NotificationEmailEvent;
import com.pinapp.notifications_client.autogenerated.events.notification.NotificationPushCreatedEvent;
import com.pinapp.notifications_client.autogenerated.events.notification.NotificationSmsCreatedEvent;
import com.pinapp.notifications_client.common.infrastructure.event.producer.KafkaProducer;
import com.pinapp.notifications_client.notification.domain.event.NotificationEmailCreatedDomainEvent;
import com.pinapp.notifications_client.notification.domain.port.NotificationEvent;
import com.pinapp.notifications_client.notification.domain.event.NotificationPushCreatedDomainEvent;
import com.pinapp.notifications_client.notification.domain.event.NotificationSmsCreatedDomainEvent;
import com.pinapp.notifications_client.notification.infrastructure.event.mapper.NotificationEventMapper;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

@Component
@RequiredArgsConstructor
@Slf4j
public class NotificationEventProducer implements NotificationEvent {

    private final KafkaProducer kafkaProducer;

    private final NotificationEventMapper notificationEventMapper;

    @Value("${app.kafka.topics.notifications}")
    private String topic;


    @Override
    public void sendEmailNotification(NotificationEmailCreatedDomainEvent event) {
        log.info("Sending notification EMAIL event to topic: {}. Event: {}", topic, event);
        NotificationEmailEvent notificationEmailEvent=notificationEventMapper.mapToNotificationEmailEvent(event);
        kafkaProducer.send(topic, notificationEmailEvent);
    }

    @Override
    public void sendSmsNotification(NotificationSmsCreatedDomainEvent event) {
        log.info("Sending notification SMS event to topic: {}. Event: {}", topic, event);
        NotificationSmsCreatedEvent notificationSmsCreatedEvent =notificationEventMapper.mapToNotificationSmsCreatedEvent(event);
        kafkaProducer.send(topic, notificationSmsCreatedEvent);
    }

    @Override
    public void sendPushNotification(NotificationPushCreatedDomainEvent event) {
        log.info("Sending notification SMS event to topic: {}. Event: {}", topic, event);
        NotificationPushCreatedEvent notificationPushCreatedEvent= notificationEventMapper.mapToNotificationPushCreatedEvent(event);
        kafkaProducer.send(topic, notificationPushCreatedEvent);
    }
}
