package com.pinapp.notifications_api.notification.infrastructure.event.consumer.specific;

import com.pinapp.notifications_api.autogenerated.events.notification.NotificationPushCreatedEvent;
import com.pinapp.notifications_api.common.application.Mediator;
import com.pinapp.notifications_api.common.infrastructure.event.consumer.EventSpecificConsumer;
import com.pinapp.notifications_api.notification.application.push.NotificationPushCommand;
import com.pinapp.notifications_api.notification.infrastructure.event.mapper.NotificationEventMapper;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.messaging.Message;
import org.springframework.stereotype.Component;

@Component
@Slf4j
@RequiredArgsConstructor
public class NotificationPushSpecificConsumer implements EventSpecificConsumer<NotificationPushCreatedEvent> {

    private final Mediator mediator;
    private final NotificationEventMapper notificationEventMapper;

    @Override
    public void accept(Message<NotificationPushCreatedEvent> genericRecordMessage) {
        log.info("UserEmailUpdatedSpecificConsumer message: {}", genericRecordMessage.toString());
        NotificationPushCommand command = notificationEventMapper.mapToNotificationPushCommand(genericRecordMessage.getPayload());
        mediator.dispatch(command);
    }

    @Override
    public String getSchema() {
        return NotificationPushCreatedEvent.getClassSchema().getFullName();
    }
}
