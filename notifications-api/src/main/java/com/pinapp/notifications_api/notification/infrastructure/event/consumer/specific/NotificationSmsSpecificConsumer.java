package com.pinapp.notifications_api.notification.infrastructure.event.consumer.specific;


import com.pinapp.notifications_api.autogenerated.events.notification.NotificationSmsCreatedEvent;
import com.pinapp.notifications_api.common.application.Mediator;
import com.pinapp.notifications_api.common.infrastructure.event.consumer.EventSpecificConsumer;
import com.pinapp.notifications_api.notification.application.sms.NotificationSmsCommand;
import com.pinapp.notifications_api.notification.infrastructure.event.mapper.NotificationEventMapper;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.messaging.Message;
import org.springframework.stereotype.Component;

@Component
@Slf4j
@RequiredArgsConstructor
public class NotificationSmsSpecificConsumer implements EventSpecificConsumer<NotificationSmsCreatedEvent> {

    private final Mediator mediator;
    private final NotificationEventMapper notificationEventMapper;

    @Override
    public void accept(Message<NotificationSmsCreatedEvent> genericRecordMessage) {
        log.info("UserDeletedSpecificConsumer message: {}", genericRecordMessage.toString());
        NotificationSmsCommand command = notificationEventMapper.mapToNotificationSmsCommand(genericRecordMessage.getPayload());
        mediator.dispatch(command);
    }

    @Override
    public String getSchema() {
        return NotificationSmsCreatedEvent.getClassSchema().getFullName();
    }
}
